    rom[0x7FD6] = 0xF4;
    rom[0x7FD7] = 0x00;
    rom[0x7FD8] = 0xE4;
    rom[0x7FD9] = 0x02;
    rom[0x7FDC] = 0x00; rom[0x7FDD] = 0x00;
    rom[0x7FDE] = 0x00; rom[0x7FDF] = 0x00;
    rom[0x7FFC] = 0x00; rom[0x7FFD] = 0x00;
    std::memset(rom.data() + 0xFFC0, ' ', 21);
    std::memcpy(rom.data() + 0xFFC0, "SUPER MARIO KART", 16);
    rom[0xFFD5] = 0x31;
    rom[0xFFD6] = 0x05;
    rom[0xFFD7] = 0x09;
    rom[0xFFD8] = 0x01;
    rom[0xFFD9] = 0x01;
