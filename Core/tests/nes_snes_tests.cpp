static int nonBlack(const u32* p, int w, int h) {
    int n = 0;
    for (int y = 0; y < h; ++y)
        for (int x = 0; x < w; x += 8)
            if ((p[y * w + x] & 0x00FFFFFF) != 0) ++n;
    return n;
}

static int greenPixels(const u32* p, int w, int h) {
    int n = 0;
    for (int y = 0; y < h; ++y)
        for (int x = 0; x < w; x += 8) {
            u32 c = p[y * w + x];
            int r = (c >> 16) & 0xFF, g = (c >> 8) & 0xFF, b = c & 0xFF;
            if (g > 80 && g > r + 40 && g > b + 40) ++n;
        }
    return n;
}

